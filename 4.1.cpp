#include <iostream>
#include <cmath>
#include <cstdlib>
#include <ctime>
using namespace std;

/**
 * @brief - выводит элементы массива на экран
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 *
 * @details Проходит по массиву от 0 до size-1 и выводит каждый элемент,
 * разделяя их пробелом. Не добавляет перевод строки в конце.
 */
void print_mass(int* mass, int size);

/**
 * @brief - заполняет массив случайными числами в диапазоне [-100; 100]
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 *
 * @details Использует функцию rand() для генерации чисел.
 * Формула: rand() % 201 - 100.
 * Также сразу выводит сгенерированные числа на экран.
 * Требуется предварительный вызов srand() в main().
 */
void random_massive(int* mass, int size);

/**
 * @brief - заполняет массив числами, введенными пользователем вручную
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 *
 * @details Запрашивает ввод каждого элемента по очереди с подсказкой индекса.
 * После ввода сразу вызывает print_mass() для отображения результата.
 */
void manual_massive(int* mass, int size);

/**
 * @brief - вычисляет сумму всех однозначных чисел в массиве
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массива
 * @return - сумма элементов, модуль которых меньше 10 (|x| < 10)
 *
 * @details Учитываются числа от -9 до 9 включительно.
 * Проверка осуществляется через abs(mass[i]) < 10.
 */
int one_digit_sum(int* mass, int size);

/**
 * @brief - разворачивает массив в обратном порядке
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 *
 * @details Меняет местами элементы симметрично относительно центра:
 * первый с последним, второй с предпоследним и т.д.
 * Цикл выполняется до size / 2. Используется функция swap().
 */
void reverse_mass(int* mass, int size);

/**
 * @brief - находит минимальный и максимальный элементы, затем разворачивает
 *          часть массива, находящуюся строго между ними
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 *
 * @details 1. Находит индексы минимального (min) и максимального (max) элементов.
 *          2. Определяет start (меньший индекс) и end (больший индекс).
 *          3. Вызывает reverse_mass() для подмассива, начинающегося со смещением
 *             (start + 1) и имеющего длину (end - start - 1).
 *          Если min и max соседние или совпадают, подмассив будет пустым.
 */
void minmax_reverse_swap(int* mass, int size);

/**
 * @brief - ищет первую справа пару соседних элементов с одинаковыми знаками,
 *          произведение которых меньше заданного числа
 * @param mass - указатель на первый элемент массива
 * @param size - количество элементов в массиве
 * @param number - пороговое значение для произведения
 * @return - индекс первого элемента пары (i), если найдено;
 *           неопределенное значение (ошибка логики), если не найдено (в исходном коде нет return вне цикла)
 *
 * @details Поиск ведется справа налево (от size-2 до 0).
 * Пропускает пары с разными знаками (одно отрицательное, другое положительное).
 * Если знаки одинаковы и mass[i] * mass[i+1] < number, возвращает индекс i.
 *
 * @warning В исходном коде отсутствует оператор return после цикла.
 * Если пара не найдена, поведение функции не определено (возврат мусора).
 * Рекомендуется добавить 'return -1;' в конец функции.
 */
int search_pair(int* mass, int size, int number);

/**
 * @brief - точка входа в программу
 * @return 0, если программа выполнена корректно
 *
 * @details Алгоритм работы программы:
 * 1. Инициализирует генератор случайных чисел (srand).
 * 2. Запрашивает размер массива n.
 * 3. Предлагает выбор способа заполнения: случайно (1) или вручную (2).
 * 4. Создает динамический массив new int[n].
 * 5. Запрашивает контрольное число (number) для задачи №3.
 * 6. Выполняет три задания:
 *    - Задание 1: Сумма однозначных чисел (one_digit_sum).
 *    - Задание 2: Разворот части массива между min и max (minmax_reverse_swap) и вывод.
 *    - Задание 3: Поиск пары элементов (search_pair) и вывод индекса или сообщения об отсутствии.
 *
 * @note Память под массив выделяется динамически, но в данном коде не освобождается (нет delete[]).
 */
int main()
{
    // настройка локали для поддержки русского языка
    setlocale(LC_ALL, "ru_RU.UTF-8");

    // инициализация генератора случайных чисел текущим временем
    srand(time(0)); // генерация псевдослучайных чисел через время на ПК

    int n, input;

    // ввод размера массива
    cout << "Введите размер массива: ";
    cin >> n;

    // выбор способа заполнения
    cout << "1-Случайная генерация чисел\n2-Ручной ввод чисел\n";
    cin >> input;

    // создание динамического массива
    int* mass = new int[n];

    // заполнение массива в зависимости от выбора
    switch (input) {
    case 1:
        random_massive(mass, n);
        break;
    case 2:
        manual_massive(mass, n);
        break;
    default:
        cout << "Ошибка ввода";
        // В случае ошибки ввода массив остается неинициализированным
    }

    // ввод контрольного числа для поиска пары
    cout << endl << "Введите заданное число (для произведения 2-х элементов): ";
    cin >> input;

    // --- Решение задач ---

    // 1. Сумма однозначных чисел
    cout << "1. " << one_digit_sum(mass, n) << endl;

    // 2. Разворот между min и max
    cout << "2. ";
    minmax_reverse_swap(mass, n);
    print_mass(mass, n);

    // 3. Поиск пары элементов
    cout << endl << "3. ";
    int pair_index = search_pair(mass, n, input);

    // Проверка результата ( -1 означает неудачу)
    if (pair_index == -1)
        cout << "Такой пары нет в данном массиве\n";
    else
        cout << "Индекс пары: " << pair_index;
    // Освобождение памяти
    return 0;
}

// --- Реализация функций ---

void print_mass(int* mass, int size) {
    for (int i = 0; i < size; i++) {
        cout << mass[i] << ' ';
    }
}

void random_massive(int* mass, int size) {
    for (int i = 0; i < size; i++) {
        // Генерация числа в диапазоне [-100, 100]
        mass[i] = rand() % 201 - 100;
        cout << mass[i] << ' ';
    }
}

void manual_massive(int* mass, int size) {
    for (int i = 0; i < size; i++) {
        cout << "Введите " << i << " элемент массива: ";
        cin >> mass[i];
    }
    print_mass(mass, size);
}

int one_digit_sum(int* mass, int size) {
    int sum = 0;
    for (int i = 0; i < size; i++) {
        // Проверка: является ли число однозначным (-9..9)
        if (abs(mass[i]) < 10) {
            sum += mass[i];
        }
    }
    return sum;
}

void reverse_mass(int* mass, int size) {
    // Обмен элементов симметрично от краев к центру
    for (int i = 0; i < size / 2; i++) {
        swap(mass[i], mass[size - 1 - i]);
    }
}

void minmax_reverse_swap(int* mass, int size) {
    int min = 0, max = 0;
    // Поиск индексов минимального и максимального элементов
    for (int i = 1; i < size; i++) {
        if (mass[min] > mass[i]) min = i;
        if (mass[max] < mass[i]) max = i;
    }

    // Определение границ диапазона для разворота
    int start = (min < max) ? min : max;
    int end = (min >= max) ? min : max;

    // Разворот подмассива между найденными элементами
    // mass + start + 1 указывает на элемент сразу после первого из пары (min/max)
    // end - start - 1 вычисляет количество элементов между ними
    reverse_mass(mass + start + 1, end - start - 1);
}

int search_pair(int* mass, int size, int number) {
    // Поиск справа налево
    for (int i = size - 2; i >= 0; i--) {
        // Пропуск пар с разными знаками
        if ((mass[i] < 0 && mass[i + 1] >= 0) || (mass[i + 1] < 0 && mass[i] >= 0))
            continue;
        // Проверка произведения
        else if (mass[i] * mass[i + 1] < number)
            return i;
    }
    return -1;
}